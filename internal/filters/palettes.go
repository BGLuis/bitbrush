// namedPalette resolves a palette name to its colour list, or nil when the
// caller should fall back to its default (non-palette) behaviour.
func namedPalette(name string) []palette.RGB {
	switch name {
	case "", "none", "custom":
		return nil
	}
	return retroPalettes[name]
}

